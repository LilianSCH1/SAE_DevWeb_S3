<h4> QU'EST-CE QU'UN COOKIE ? </h4>
<p>
    Un cookie est un petit fichier texte déposé sur votre terminal lors de la visite du site MyPulse.
    <br>
    Il permet de mémoriser des informations comme vos préférences de navigation ou votre session de vote, facilitant une expérience fluide sans compromettre la sécurité.​
</p>
<br>

<h4> TYPES DE COOKIES UTILISÉS </h4>
<p>
    Nous utilisons différents types de cookies pour améliorer votre expérience sur MyPulse :
    <br>
    <br>
    - Cookies essentiels : Indispensables au fonctionnement, ils gèrent l'authentification, les votes uniques par catégorie et les sessions utilisateur.
    <br>
    Aucun consentement n'est requis.
    <br>
    <br>
    - Cookies analytiques : Anonymes, ils mesurent l'audience (pages vues, classements consultés) pour optimiser la plateforme. 
    <br>
    Consentement préalable via notre bandeau.
    <br>
    <br>
    - Cookies fonctionnels : Personnalisent l'interface (thèmes sombre/clair, notifications) et intègrent les partages sociaux pour les résultats de concours.
    <br>
    Aucun cookie publicitaire tiers n'est utilisé ; durée maximale de 6 mois, renouvelable avec consentement.
</p>
<br>

<h4> GESTION ET CONSENTEMENT </h4>
<p>
    Lors de votre première visite, un bandeau collecte votre consentement exprès pour les cookies non essentiels.
    <br>
    Modifiez vos préférences via l'icône en bas d'écran ou les paramètres de votre navigateur
    <br>
    Refuser les cookies analytiques n'empêche pas l'accès aux votes ou classements.
</p>
<br>

<h4> VOS DROITS </h4>
<p>
    Conformément au RGPD, contactez mypulse.company@gmail.com pour accéder, rectifier ou supprimer les données cookies.
    <br>
    Nous conservons les logs essentiels pendant 13 mois pour des raisons de sécurité.
</p>