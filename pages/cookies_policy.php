<h1> Qu'est-ce qu'un Cookie ? </h1>
<p>
Un cookie est un petit fichier texte déposé sur votre terminal lors de la visite du site MyPulse. Il permet de mémoriser des informations comme vos préférences de navigation ou votre session de vote, facilitant une expérience fluide sans compromettre la sécurité.​
</p>

<h1> Types de Cookies Utilisés </h1>
<p>
Nous utilisons différents types de cookies pour améliorer votre expérience sur MyPulse :​
Cookies essentiels : Indispensables au fonctionnement, ils gèrent l'authentification, les votes uniques par catégorie et les sessions utilisateur. Aucun consentement n'est requis.​

Cookies analytiques : Anonymes, ils mesurent l'audience (pages vues, classements consultés) pour optimiser la plateforme. Consentement préalable via notre bandeau.​

Cookies fonctionnels : Personnalisent l'interface (thèmes sombre/clair, notifications) et intègrent les partages sociaux pour les résultats de concours.​
Aucun cookie publicitaire tiers n'est utilisé ; durée maximale de 6 mois, renouvelable avec consentement.​
</p>

<h1> Gestion et Consentement </h1>
<p>
Lors de votre première visite, un bandeau collecte votre consentement exprès pour les cookies non essentiels. Modifiez vos préférences via l'icône en bas d'écran ou les paramètres de votre navigateur. Refuser les cookies analytiques n'empêche pas l'accès aux votes ou classements.​
</p>

<h1> Vos Droits </h1>
<p>
Conformément au RGPD, contactez support@mypulse.com pour accéder, rectifier ou supprimer les données cookies. Nous conservons les logs essentiels pendant 13 mois pour des raisons de sécurité.​
</p>