<h1> Engagement de l'Entreprise </h1>
<p>
MyPulse, en tant que responsable de traitement, respecte strictement le RGPD et la loi Informatique et Libertés. Nous protégeons les données des utilisateurs (votants, certifiés, admins, invités) avec chiffrement et audits réguliers.​​

<h1> Données Collectées </h1>
<p>
Comptes utilisateurs : Email unique, nom, prénom, mot de passe haché, rôle (votant/certifié/admin/invit), date d'inscription.

Activité : Votes (date, contenu), soumissions de contenus (titre, média, catégorie), notifications, IP des invités.

Certifiés : Réseau social, statut de vérification. Collecte minimale, uniquement pour les fonctionnalités essentielles.​​
</p>

<h1> Finalités et Base Légale </h1>
<p>
Données traitées pour gérer votes, valider contenus, publier classements et envoyer notifications (intérêt légitime). Consentement pour options comme connexions sociales. Conservation : 5 ans post-suppression compte, ou durée des concours.​
</p>

<h1> Partage et Sécurité </h1>
<p>
Aucun partage avec tiers sans consentement ; seuls prestataires internes (hébergement sécurisé) accèdent aux données. Mesures : HTTPS, limitation d'accès par rôle, backups chiffrés.​​
</p>

