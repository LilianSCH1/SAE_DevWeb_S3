<h4> ENGAGEMENT DE L'ENTREPRISE </h4>
<p>
MyPulse, en tant que responsable de traitement, respecte strictement le RGPD et la loi Informatique et Libertés.
<br>
Nous protégeons les données des utilisateurs (votants, certifiés, admins, invités) avec chiffrement et audits réguliers.
</p>
<br>

<h4> DONNÉES COLLECTÉES </h4>
<p>
Comptes utilisateurs : Email unique, nom, prénom, mot de passe haché, rôle (votant/certifié/admin/invité), date d'inscription.
<br>
Activité : Votes (date, contenu), soumissions de contenus (titre, média, catégorie), notifications, IP des invités.
<br>
Certifiés : Réseau social, statut de vérification. Collecte minimale, uniquement pour les fonctionnalités essentielles.
</p>
<br>

<h4> FINALITÉS ET BASE LÉGALE </h4>
<p>
Données traitées pour gérer votes, valider contenus, publier classements et envoyer notifications (intérêt légitime).
<br>
Consentement pour options comme connexions sociales. Conservation : 5 ans post-suppression compte, ou durée des concours.
</p>
<br>

<h4> PARTAGE ET SÉCURITÉ </h4>
<p>
Aucun partage avec tiers sans consentement ; seuls prestataires internes (hébergement sécurisé) accèdent aux données.
<br> 
Mesures : HTTPS, limitation d'accès par rôle, backups chiffrés.
</p>
<br>

<h4> COOKIES ET TECHNOLOGIES SIMILAIRES </h4>
<p>
Vos Droits RGPD
<br>
Accès, rectification, effacement via mypulse.company@gmail.com.
<br>
Opposition, limitation, portabilité ; rétractation du consentement.
<br>
Délégué à la Protection des Données disponible pour plaintes CNIL.
</p>